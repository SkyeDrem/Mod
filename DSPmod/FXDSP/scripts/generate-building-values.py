"""Reproduce exchange prices and review tables from local game recipe facts (no Unity dependency)."""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'docs/data/production-recipes.json'
SPECIAL_BASES = {1120: '可从气态行星直接采集的氢', 1208: '仅消耗能量获取的临界光子，作为无物料来源基准'}
UNITS = {1131, 5001, 5002, 5003, 5101, 5102, 5103, 5111, 5112}
PRICING_SCHEME = 'one_half_plus_half'

def processing_factor(recipe):
    return Fraction(3, 2) + Fraction(len({item for item, count in zip(recipe['Items'], recipe['ItemCounts']) if count > 0}), 2)

def load_native(directory, locale):
    def load(kind):
        return json.loads(next(directory.glob('*-' + kind + 'ProtoSet.json')).read_text(encoding='utf-8'))['dataArray']
    translations = {}
    if locale:
        for line in locale.read_text(encoding='utf-16').splitlines():
            parts = line.split('\t')
            if len(parts) >= 4: translations[parts[0]] = parts[-1]
    def name(value): return translations.get(value, value)
    items = [{key: i[key] for key in ('ID', 'Type', 'CanBuild', 'StackSize', 'GridIndex')} | {'Name': name(i['Name'])} for i in load('Item')]
    recipes = [{key: r[key] for key in ('ID', 'Type', 'TimeSpend', 'Items', 'ItemCounts', 'Results', 'ResultCounts')} | {'Name': name(r['Name'])} for r in load('Recipe')]
    DATA.parent.mkdir(exist_ok=True)
    DATA.write_text(json.dumps({'Source': '本机 DSP resources.assets 原型表；仅保留配方事实与物品名称，不分发游戏二进制。', 'Items': items, 'Recipes': recipes}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def generate(check=False):
    data = json.loads(DATA.read_text(encoding='utf-8'))
    items = {i['ID']: i for i in data['Items']}
    recipes = sorted(data['Recipes'], key=lambda r: r['ID'])
    values, chosen, active = {}, {}, set()
    bases = {i['ID']: '原矿/水/木材等直接采集物' for i in items.values() if i['Type'] == 1}
    bases.update({i: '黑雾专属掉落' for i in range(5201, 5207)})
    bases.update(SPECIAL_BASES)
    def value(item_id):
        if item_id in values: return values[item_id]
        if item_id in active: raise ValueError('循环配方: ' + str(item_id))
        if item_id in bases:
            values[item_id] = Fraction(1); return values[item_id]
        active.add(item_id)
        try:
            if item_id == 2207:
                chosen[item_id] = {'ID': 0, 'Name': '能量枢纽充电', 'Items': [2206], 'ItemCounts': [1], 'Results': [2207], 'ResultCounts': [1], 'Type': 0}
                result = value(2206) * processing_factor(chosen[item_id])
            else:
                candidates = [r for r in recipes if item_id in r['Results']]
                if not candidates: raise ValueError('缺少物料来源: ' + str(item_id))
                recipe = candidates[0]
                # All coproducts share the batch cost by output count; do not count the batch twice.
                result = sum((value(i) * n for i, n in zip(recipe['Items'], recipe['ItemCounts'])), Fraction(0)) * processing_factor(recipe) / sum(recipe['ResultCounts'])
                chosen[item_id] = recipe
            if result <= 0: raise ValueError('非正价格: ' + str(item_id))
            values[item_id] = result
            return result
        finally: active.remove(item_id)
    for item_id in items: value(item_id)
    eligible = [i for i in items.values() if i['CanBuild'] or i['ID'] in UNITS]
    eligible.sort(key=lambda i: i['ID'])
    ceil = lambda v: (v.numerator + v.denominator - 1) // v.denominator
    def exact(v): return str(v.numerator) if v.denominator == 1 else f'{v.numerator}/{v.denominator}'
    def named(item_id): return f"{items[item_id]['Name']} [{item_id}]"
    def formula(r):
        return ' + '.join(f'{n} {named(i)}' for i, n in zip(r['Items'], r['ItemCounts'])) + ' → ' + ' + '.join(f'{n} {named(i)}' for i, n in zip(r['Results'], r['ResultCounts']))
    def calculation(item_id):
        r = chosen[item_id]
        parts = ' + '.join(f'{n}×{exact(values[i])}' for i, n in zip(r['Items'], r['ItemCounts']))
        return f'({parts})×{processing_factor(r)}/{sum(r["ResultCounts"])} = {exact(values[item_id])}'
    digest = hashlib.sha256(DATA.read_bytes()).hexdigest()
    cs = ['// Generated by scripts/generate-building-values.py; do not edit prices by hand.', '// Recipe facts SHA256: ' + digest, 'using System.Collections.Generic;', '', 'namespace FXDSP.Core', '{', '    public static class BuildingValues', '    {', '        private static readonly Dictionary<int, long> Prices = new Dictionary<int, long>', '        {']
    for item in eligible: cs.append(f'            {{ {item["ID"]}, {ceil(values[item["ID"]])}L }}, // {item["Name"]}')
    cs += ['        };', '        public static bool TryGet(int itemId, out long price) { return Prices.TryGetValue(itemId, out price); }', '    }', '}', '']
    doc = ['# 建筑币定价与全材料配方核对表（0.18.4）', '', '当前采用材料种类方案：每道加工乘以（1.5 + 不同输入物品种类数 ÷ 2）；不加入加工时间倍数。文档路径保留历史名称，表内价格为当前正式值。', '', f'来源：本机游戏原型表，共 {len(items)} 种物品、{len(recipes)} 条配方、{len(eligible)} 项可兑换物品。原始事实表校验：`{digest}`。', '',
        '## 计算约定', '', '1. 原矿、珍奇矿石、水、原油、木材及植物燃料的基准价值为 1。硫酸、有机晶体、重氢不因可直接采集而视为原矿，按普通加工配方递归计算。六种黑雾专属掉落均为 1。',
        '2. 每道生产的单件价值 = 全部投入材料价值总和 ×（1.5 + 不同输入材料种类数 ÷ 2）÷ 本批总产出数量。种类按正数量输入的不同物品 ID 计数，不按件数或展开后的原矿种类计数。递归应用至每道上游加工，不计生产时间、电耗、增产和建筑速度。中间材料保留精确分数，最终建筑兑换价向上取整；回收使用同一个整数价格，手续费另计。',
        '3. 多配方物品按原版配方 ID 最小的普通配方计算，排除后续高效、珍奇替代及循环路线。硅石虽有碎石配方，因自身为原矿仍为 1。所有候选配方在文末列出，便于调整定价基准。',
        '4. 多产物按产出件数均摊整批价值，例如 2 原油 → 1 氢 + 2 精炼油，输入只有原油一种，倍数为 2，精炼油为 4/3。氢的基准来源采用气态行星直接采集，独立定为 1；不会再给精炼油叠加一次氢成本。',
        '5. 无物料配方的临界光子以 1 为基准；满蓄电器按空蓄电器充电这一道加工计算，输入仅空蓄电器一种，价值为空蓄电器的 2 倍。这两项为补足物料图所需的明确约定。',
        '6. 重氢采用常规对撞机配方（10 氢 → 5 重氢），价值 4。分馏塔的 100 氢 → 1 重氢是概率描述，未成功的氢回流，不可解释为实际消耗 100 氢；它属于另一条路线，本版未将其替换成重氢的定价基准。',
        '7. 交付平台仍只在制造台生产，不纳入建筑币兑换。下表涵盖原版全部建筑、地基、三种物流运输单位和五种战斗单位；不加入材料账户互换。', '',
        '示例：铁板与齿轮各只有一种输入，倍数为 2，铁板 = 2，齿轮 = 4；传送带有两种输入，倍数为 5/2，传送带 = (2×2 + 4)×(5/2)/3 = 20/3，兑换价向上取整为 **7 建筑币**。', '', '## 可兑换建筑与单位', '', '| ID | 物品 | 本批配方 | 逐项代值计算 | 建筑币/件（向上取整） |', '| --- | --- | --- | --- | ---: |']
    for item in eligible:
        i = item['ID']; doc.append(f'| {i} | {item["Name"]} | {formula(chosen[i])} | {calculation(i)} | **{ceil(values[i]):,}** |')
    doc += ['', '## 材料、原矿、矩阵与其他物品', '', '| ID | 物品 | 定价来源或配方 | 代值计算 | 精确价值/件 |', '| --- | --- | --- | --- | ---: |']
    eligible_ids = {i['ID'] for i in eligible}
    for i in sorted(items):
        if i in eligible_ids: continue
        if i in bases: source, calc = bases[i], '基准 1'
        else: source, calc = formula(chosen[i]), calculation(i)
        doc.append(f'| {i} | {items[i]["Name"]} | {source} | {calc} | {exact(values[i])} |')
    doc += ['', '## 多配方核对', '', '“采用”表示计算建筑币时递归使用的路线；其它路线仅列配方，不参与压低当前固定比价。', '', '| 目标物品 | 配方 ID | 本批配方 | 采用 |', '| --- | ---: | --- | --- |']
    for i in sorted(items):
        candidates = [r for r in recipes if i in r['Results']]
        if len(candidates) < 2: continue
        for r in candidates: doc.append(f'| {named(i)} | {r["ID"]} | {formula(r)} | {"是" if i not in bases and chosen[i]["ID"] == r["ID"] else "否"} |')
    market_ids = {i['ID'] for i in items.values() if i['StackSize'] > 0 and (1000 <= i['ID'] < 2000 or 5201 <= i['ID'] <= 5206 or 6001 <= i['ID'] <= 6006) and i['ID'] not in eligible_ids}
    assert market_ids | eligible_ids == set(items) and not market_ids & eligible_ids
    doc += ['', '## 行情目录完整性（0.15 修订）', '', '黑雾掉落 5201～5206 全部归材料，矩阵页仅保留六种工厂矩阵。其余可堆叠原料、材料、产品、弹药及消耗品均纳入选择目录。建筑、物流运输单位和战斗单位走建筑币兑换；沙土 1099 归消耗品，通过游戏独立沙土总量存取，不走背包物品或交付塔。', '',
        f'行情目录包含 {len(market_ids)} 种物品，初始均未选中。与 {len(eligible_ids)} 项兑换物品合计覆盖原型表全部 {len(items)} 种物品，无未说明的遗漏。', '',
        '复算：在项目根目录执行 `python scripts/generate-building-values.py`；加 `--check` 可验证事实表、此文档与游戏价格源码完全一致。', '']
    outputs = {ROOT / 'src/FXDSP/Core/BuildingValues.cs': '\n'.join(cs), ROOT / 'docs/building-values-0.14.0.md': '\n'.join(doc)}
    for path, content in outputs.items():
        if check:
            if path.read_text(encoding='utf-8') != content: raise ValueError('生成结果不同: ' + str(path))
        else: path.write_text(content, encoding='utf-8')
    assert values[1101] == 2 and values[1201] == 4 and values[2001] == Fraction(20, 3)
    assert len(eligible) == len(eligible_ids) and all(ceil(values[i]) > 0 for i in eligible_ids)
    print(f'Verified {len(items)} item values, {len(recipes)} recipes, {len(eligible)} exchange prices. Conveyor = {exact(values[2001])}, rounded = {ceil(values[2001])}.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--native-directory', type=Path); parser.add_argument('--locale', type=Path); parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.native_directory: load_native(args.native_directory, args.locale)
    generate(args.check)


